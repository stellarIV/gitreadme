import { RepoAnalysis } from "./types";

export function generateMarkdownDoc(analysis: RepoAnalysis, docType: "readme" | "architecture" = "readme"): string {
  const { metadata, techStack, architecture, setupGuide, nonFunctional, roast } = analysis;

  if (docType === "architecture") {
    return `# Architecture Blueprint: ${metadata.name}

> Auto-generated by [gitreadme](https://gitreadme.dev) (RepoIntel).

## Executive Overview
${architecture.textualOverview}

## System Architecture Diagram
\`\`\`mermaid
${architecture.diagramMermaid}
\`\`\`

## Core Architectural Subsystems
${architecture.components
  .map(
    (c) => `### ${c.name}
- **Role:** ${c.role}
- **Technology:** \`${c.tech}\`
- **Key Locations:** ${c.paths.map((p) => `\`${p}\``).join(", ")}
`
  )
  .join("\n")}

## Primary Entry Points
| Entry Point | Path | Description |
| :--- | :--- | :--- |
${architecture.entryPoints.map((e) => `| **${e.name}** | \`${e.path}\` | ${e.description} |`).join("\n")}

## Data Flow Pipeline
${architecture.dataFlow.map((step, idx) => `${idx + 1}. ${step}`).join("\n")}

## Non-Functional Requirements & Security
- **Authentication:** ${nonFunctional.authStrategy}
- **Caching:** ${nonFunctional.caching}
- **Rate Limiting:** ${nonFunctional.rateLimiting}
- **Testing Maturity:** \`${nonFunctional.testingMaturity.toUpperCase()}\`
- **Observability:** ${nonFunctional.observability}
`;
  }

  // Standard README.md
  const badges = [
    metadata.language ? `![Language](https://img.shields.io/badge/language-${encodeURIComponent(metadata.language)}-blue.svg)` : "",
    metadata.license ? `![License](https://img.shields.io/badge/license-${encodeURIComponent(metadata.license)}-green.svg)` : "",
    `![Stars](https://img.shields.io/badge/stars-${metadata.stars}-yellow.svg)`,
  ]
    .filter(Boolean)
    .join(" ");

  const envVarsTable =
    setupGuide.envVars.length > 0
      ? `### Environment Variables
| Variable | Required | Default | Purpose |
| :--- | :---: | :--- | :--- |
${setupGuide.envVars
  .map(
    (v) =>
      `| \`${v.name}\` | ${v.required ? "✅" : "❌"} | \`${v.defaultValue || "None"}\` | ${v.description} |`
  )
  .join("\n")}`
      : "";

  return `# ${metadata.name}

${badges}

${metadata.description || "Living documentation, architecture breakdown, and setup guide."}

---

## ⚡ Quick Start

### 1. Prerequisites
- **Runtime:** ${setupGuide.runtimeVersion || "Node.js 18+"}
- **Package Manager:** \`${setupGuide.packageManager}\`

### 2. Installation
\`\`\`bash
# Clone the repository
git clone ${metadata.htmlUrl}.git
cd ${metadata.name}

# Install project dependencies
${setupGuide.installCommands.join("\n")}
\`\`\`

${envVarsTable ? `${envVarsTable}\n` : ""}
### 3. Local Development
\`\`\`bash
${setupGuide.devCommands.join("\n")}
\`\`\`

### 4. Running Tests & Build
\`\`\`bash
# Run test suite
${setupGuide.testCommands.join("\n")}

# Compile build
${setupGuide.buildCommands.join("\n")}
\`\`\`

---

## 🏗️ Architecture & Component Flow

${architecture.textualOverview}

\`\`\`mermaid
${architecture.diagramMermaid}
\`\`\`

---

## 🧰 Technology Stack

${techStack.map((t) => `- **${t.name}** (\`${t.category}\`): ${t.purpose}`).join("\n")}

---

## 🚀 Deployment Targets

${setupGuide.deploymentTargets.map((d) => `- **${d.target}:** ${d.notes}`).join("\n")}

${
  analysis.mode === "roast"
    ? `---

## 🔥 Repo Roast Verdict (${roast.scoreOutOf100}/100: ${roast.verdictTitle})

> *"${roast.oneLinerRoast}"*

### Sins Detected:
${roast.techSins.map((s) => `- **${s.sin}:** ${s.explanation} *(Fix: ${s.howToRedeem})*`).join("\n")}
`
    : ""
}
---

<sub>Generated with love and technical precision by [gitreadme](https://gitreadme.dev) (RepoIntel).</sub>
`;
}
